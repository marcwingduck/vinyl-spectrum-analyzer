"""Renders the picture page's icons: spectrum bars of round LEDs in the panel's colors, lilac
at the bottom fading into sage on top, lilac peak dots, on black.

    python3 icons/render_icons.py

Writes the PNGs next to this script to look at, and src/page_icons.h, which the firmware
serves them from: the home screen icon (Android takes it from the manifest, iOS from the
apple-touch-icon) and the browser tab's favicon. Drawn 4x oversized and scaled down, so the
dots get soft edges.
"""

from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).parent
HEADER = HERE.parent / "src" / "page_icons.h"

SAGE, LILAC = (185, 233, 189), (229, 181, 255)  # as in setup()
# per icon size: lit LEDs per bar, and the row of each bar's peak dot from the bottom (1 is
# the lowest, 0 for none). Fewer, bigger LEDs for the favicon, or they blur into one.
# A peak dot needs a dark LED below it, or it reads as part of its bar. Uneven, as if caught
# mid-beat.
BARS = [4, 6, 3, 2, 5, 3, 2]
PEAKS = [6, 0, 5, 4, 7, 5, 4]
SMALL_BARS = [3, 4, 1, 2]
SMALL_PEAKS = [0, 0, 3, 4]
MARGIN = 0.16  # around the grid, of the icon's size: inside the round masks launchers put on it
OFF = (14, 14, 18)  # unlit LEDs: barely there, so the bars stand out
SS = 4


def mix(a, b, t):
    return tuple(round(a[k] + (b[k] - a[k]) * t) for k in range(3))


def icon(size, bars, peaks):
    grid = len(bars)
    big = size * SS
    img = Image.new("RGB", (big, big), (0, 0, 0))
    d = ImageDraw.Draw(img)
    pitch = big * (1 - 2 * MARGIN) / grid
    r = pitch * 0.4
    for col in range(grid):
        for row in range(grid):  # from the bottom
            if row < bars[col]:
                c = mix(LILAC, SAGE, row / (grid - 1))
            elif row + 1 == peaks[col]:
                c = LILAC
            else:
                c = OFF
            x = big * MARGIN + (col + 0.5) * pitch
            y = big * MARGIN + (grid - 1 - row + 0.5) * pitch
            d.ellipse([x - r, y - r, x + r, y + r], fill=c)
    # a palette of a few dozen colors is enough for soft dot edges and a fraction of the bytes
    return img.resize((size, size), Image.LANCZOS).quantize(48, dither=Image.Dither.NONE)


def png(img):
    out = BytesIO()
    img.save(out, "PNG", optimize=True)
    return out.getvalue()


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    return f"static const uint8_t {name}[] = {{\n    {body}}};\n"


if __name__ == "__main__":
    icons = {"ICON_192": 192, "ICON_512": 512, "FAVICON": 32}
    parts = [
        "#pragma once\n\n// Generated by icons/render_icons.py; edit that and run it again.\n\n#include <stdint.h>\n"
    ]
    for name, size in icons.items():
        img = icon(size, SMALL_BARS, SMALL_PEAKS) if size < 64 else icon(size, BARS, PEAKS)
        file = HERE / ("favicon.png" if name == "FAVICON" else f"icon-{size}.png")
        img.save(file, optimize=True)
        data = png(img)
        parts.append(c_array(name, data))
        print(f"{file.name}: {len(data)} bytes")
    HEADER.write_text("\n".join(parts))
